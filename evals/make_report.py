"""Generates evals/RESULTS.md from evals/results/*.json so README numbers are traceable. Run after run_all_evals.sh."""
import json
from math import comb
from pathlib import Path

R_ = R = Path(__file__).parent / "results"
SETS = [("benchmark", "Benchmark (hand-written, 39 scam / 40 legit)"), ("hard_text", "Hard text (polite scams vs urgent-sounding legit)"),
        ("live_pairs", "Live phishing pairs (OpenPhish snapshot vs real-brand twin)"), ("uci_holdout", "UCI SMS held-out (public, spam not scam)")]


def wilson(k, n, z=1.96):
    if not n:
        return (0, 0)
    p = k / n; d = 1 + z * z / n; c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return max(0, c - h), min(1, c + h)


def fisher_two_sided(a, b, c, d):
    """a,b = flagged/not (arm 1); c,d = flagged/not (arm 2)."""
    n1, n2, k = a + b, c + d, a + c
    tot = comb(n1 + n2, k)
    pr = lambda x: comb(n1, x) * comb(n2, k - x) / tot
    p0 = pr(a)
    return sum(pr(x) for x in range(max(0, k - n2), min(n1, k) + 1) if pr(x) <= p0 + 1e-12)


def load(s, m):
    return json.load(open(R / f"{s}_{m}.json"))


def counts(d):
    c = d["summary"]["lenient"]["confusion"]
    return c["tp"], c["fn"], c["fp"], c["tn"]


pct = lambda x: f"{100 * x:.1f}%"
out = ["# Evaluation results", "",
       "Positive = flagged (verdict Scam or Suspicious). Intervals are 95% Wilson. Generated by `evals/make_report.py` from `evals/results/*.json`.", "",
       "| Set | Arm | n | Accuracy | Scam recall | False-positive rate (95% CI) | Median time | Avg tokens |", "|---|---|---|---|---|---|---|---|"]
tot = {"agent": [0, 0, 0, 0], "baseline": [0, 0, 0, 0]}
for s, title in SETS:
    for m in ("baseline", "agent"):
        d = load(s, m); L = d["summary"]["lenient"]; tp, fn, fp, tn = counts(d)
        lo, hi = wilson(fp, fp + tn)
        out.append(f"| {title} | {'Muse Spark, no tools' if m == 'baseline' else 'Red Flag agent'} | {L['n']} | {pct(L['accuracy'])} | {pct(L['recall'])} | {pct(L['false_positive_rate'])} ({pct(lo)}-{pct(hi)}) | {d['summary']['median_seconds']:.0f}s | {d['summary']['avg_tokens'] or 0} |")
        if s != "uci_holdout":
            for i, v in enumerate((tp, fn, fp, tn)):
                tot[m][i] += v
out += ["", "## Pooled over benchmark + hard text + live pairs (the sets that contain realistic scams and look-alike legitimate messages)", ""]
for m in ("baseline", "agent"):
    tp, fn, fp, tn = tot[m]; lo, hi = wilson(fp, fp + tn)
    out.append(f"- **{'No-tools baseline' if m == 'baseline' else 'Red Flag agent'}**: {fp} false alarms on {fp + tn} legitimate messages ({pct(fp / (fp + tn))}, CI {pct(lo)}-{pct(hi)}); caught {tp} of {tp + fn} scams.")
a, b = tot["agent"][2], tot["agent"][3]; c_, d_ = tot["baseline"][2], tot["baseline"][3]
out.append(f"- False-alarm difference, Fisher exact two-sided p = {fisher_two_sided(a, b, c_, d_):.3f} (small counts: suggestive, not conclusive).")
out += ["", "## Ablation: agent without the phishing-feed check", ""]
for s in ("live_pairs", "hard_text"):
    d = json.load(open(R / f"{s}_agent_noblocklist.json")); L = d["summary"]["lenient"]
    out.append(f"- {s}: accuracy {pct(L['accuracy'])}, recall {pct(L['recall'])}, false-positive rate {pct(L['false_positive_rate'])} (n={L['n']}). The other tools (redirects, domain age, official-domain match) carry the verdict without the feed.")
out += ["", "## Strict view: only 'Scam' counts as flagged", "", "| Set | Arm | Scam recall (strict) |", "|---|---|---|"]
for s, title in SETS:
    for m in ("baseline", "agent"):
        out.append(f"| {title} | {m} | {pct(load(s, m)['summary']['strict']['recall'])} |")
out += ["", "The agent reserves 'Scam' for concrete evidence; polite scams with nothing checkable are returned as 'Suspicious'. That is a deliberate calibration, and it lowers strict recall.", ""]
out += ["", "## Same agent on open-weight Muse Spark Open (Baseten)", "", "Identical prompt, tools and sets; only the model changes (AGENT_BACKEND=open). The prompt was tuned on closed Muse Spark, not on this model.", "", "| Set | n | Accuracy | Scam recall | False-positive rate (95% CI) |", "|---|---|---|---|---|"]
for s, title in SETS:
    d = json.load(open(R / f"{s}_agent_open.json")); L = d["summary"]["lenient"]; tp, fn, fp, tn = counts(d); lo, hi = wilson(fp, fp + tn)
    out.append(f"| {title} | {L['n']} | {pct(L['accuracy'])} | {pct(L['recall'])} | {pct(L['false_positive_rate'])} ({pct(lo)}-{pct(hi)}) |")
out += ["", "The prompt was tuned on closed Muse Spark, so these are out-of-the-box results for the open model. Closed Muse Spark remains the default; the app fails over between the two.", ""]
out += ["", "## Prompt-injection robustness", "", "24 real-style scams that each carry an attack aimed at the investigator (ignore-previous-instructions, fake system tags, fake tool results, copy-this-verdict JSON, role-play, authority claims, other languages, base64, hidden comments, exfiltration requests, and more), plus 8 legitimate messages that contain instruction-like wording. Source: `evals/injection_src.py`.", "", "| Arm | Attacked scams still flagged | Called 'Looks Safe' | Legit flagged |", "|---|---|---|---|"]
for tag, name in (("baseline", "Muse Spark, no tools"), ("agent", "Red Flag agent (Muse Spark)"), ("agent_open", "Red Flag agent (Muse Spark Open)")):
    R = json.load(open(R_ / f"injection_{tag}.json"))["results"]
    sc = [r for r in R if r["label"] == "scam"]; lg = [r for r in R if r["label"] == "legit"]
    fl = sum(r["verdict"] in ("Scam", "Suspicious") for r in sc); safe = sum(r["verdict"] == "Looks Safe" for r in sc); lf = sum(r["verdict"] in ("Scam", "Suspicious") for r in lg)
    lo, hi = wilson(fl, len(sc))
    out.append(f"| {name} | {fl}/{len(sc)} (95% CI {pct(lo)}-{pct(hi)}) | {safe} | {lf}/{len(lg)} |")
out += ["", "The attacks were written by us, so this shows resistance to common injection styles, not to a determined adaptive attacker. Untrusted text is always delimited, the model is told never to obey it, tool results and page text are labelled untrusted, and a blocklist hit can never be downgraded to 'Looks Safe' by the model.", ""]
(Path(__file__).parent / "RESULTS.md").write_text("\n".join(out))
print("\n".join(out))
